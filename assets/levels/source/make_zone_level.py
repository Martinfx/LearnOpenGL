def scatter(n, region, names, parent, r=2.5, lod_dist=45, has_lod=True, tries=40):
    x0, x1, z0, z1 = region
    placed = 0
    for _ in range(n):
        for _ in range(tries):
            x, z = rng.uniform(x0, x1), rng.uniform(z0, z1)
            if free(x, z, r):
                gen(names[0] if len(names) == 1 else rng.choice(names).split(':')[0], rng.choice(names), x, 0, z, parent,
                    yaw=rng.uniform(0, 360), lod_dist=lod_dist, has_lod=has_lod, foot=r)
                placed += 1
                break
    return placed


