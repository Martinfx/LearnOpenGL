def uname(base):
    used[base] = used.get(base, 0) + 1
    return base if used[base] == 1 else f'{base} {used[base]}'


def group(name, parent=''):
    lines.append(f'group "{name}" "{parent}"')


def box(name, cx, cy, cz, sx, sy, sz, mat, parent, color=(0.5, 0.5, 0.5)):
    lines.append(f'box "{uname(name)}" {cx:g} {cy:g} {cz:g} {sx:g} {sy:g} {sz:g} {color[0]:g} {color[1]:g} {color[2]:g}')
